const fs=require("node:fs");
const assert=require("node:assert/strict");
const vm=require("node:vm");
const read=p=>fs.readFileSync(p,"utf8");
const html=read("index.html"),js=read("atelier.js"),css=read("atelier.css"),media=read("media.js");
const context={window:{}};vm.runInNewContext(media,context);
const m=context.window.MAMTU_MEDIA;
assert(m,"Media config missing");
assert.equal(m.hero.length,3);
assert.equal(m.hero[0].src,"/assets/images/6.jpeg");
assert.equal(m.hero[1].src,"/assets/images/3.jpeg");
assert.equal(m.hero[2].src,"/assets/videos/1.mp4");
assert.equal(m.hero[2].type,"video");
