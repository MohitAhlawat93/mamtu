const fs=require("node:fs");
const assert=require("node:assert/strict");
const vm=require("node:vm");
const read=p=>fs.readFileSync(p,"utf8");
const pages=["index.html","about.html","gallery.html","videos.html","services.html","reviews.html","details.html","contact.html"];
const home=read("index.html"),gallery=read("gallery.html"),videos=read("videos.html"),services=read("services.html"),reviews=read("reviews.html"),contact=read("contact.html"),css=read("atelier.css"),js=read("atelier.js");
for(const page of pages){
  assert(fs.existsSync(page),"Missing "+page);
  const content=read(page);
  assert(content.includes('name="viewport"'),"Mobile viewport missing: "+page);
  assert(content.includes('name="robots" content="noindex,nofollow"'),"Staging indexing accidentally enabled: "+page);
  assert(content.includes('href="/atelier.css?v=editorial-20261120-v2"'),"Versioned CSS missing: "+page);
  assert(content.includes('src="/atelier.js?v=editorial-20261120-v2"'),"Versioned JS missing: "+page);
  assert(content.includes('/assets/mark.svg'),"Mamtu brand mark missing: "+page);
  assert(content.includes('https://wa.me/918368410417'),"WhatsApp missing: "+page);
  assert(content.includes('https://t.me/mistressmamtu'),"Telegram missing: "+page);
  for(const link of pages)assert(content.includes('href="/'+link+'"'),"Navigation missing "+link+" in "+page);
  assert(!content.includes("paryavarn complex"),"Private residential detail published: "+page);
  assert(!/PHOTO\s+0\d/i.test(content),"Visible numbered photo label remains: "+page);
  assert(!/VIDEO\s+0\d/i.test(content),"Visible numbered video label remains: "+page);
  assert(!/eight photos,? eight moods/i.test(content),"Fixed-size gallery slogan remains: "+page);
  assert(!content.includes("PRIVATE PREVIEW"),"Testing copy remains: "+page);
}
assert(fs.existsSync("assets/mark.svg"),"Brand mark asset missing");
assert(home.includes('class="useful-bits"'),"Useful-bits homepage section missing");
assert(home.includes("Saket · New Delhi"),"Useful-bits location missing");
assert(home.includes('class="home-services"'),"Homepage services preview missing");
assert(home.includes('class="home-reviews-preview"'),"Homepage reviews preview missing");
assert(home.includes("/assets/images/6.jpeg")&&home.includes("/assets/images/3.jpeg")&&home.includes("/assets/videos/1.mp4"),"Featured media changed");
assert.equal((gallery.match(/data-photo-index="/g)||[]).length,8,"Current gallery should render eight uploaded images");
assert.equal((gallery.match(/class="story-description"/g)||[]).length,8,"Every current gallery image needs a story");
assert(!gallery.includes('id="lightboxCount"'),"Visible image counter should be removed");
assert.equal((videos.match(/<video /g)||[]).length,3,"Current videos missing");
assert.equal((videos.match(/class="film-description"/g)||[]).length,3,"Video editorial notes missing");
assert.equal((services.match(/class="service-card"/g)||[]).length,6,"Services page should contain six service cards");
assert(services.includes("By arrangement"),"Services should avoid invented public pricing");
assert(reviews.includes("No public reviews"),"Reviews empty state missing");
assert(!/★|★★★★★|4\.\d\s*\/\s*5/.test(reviews),"Fabricated rating detected");
assert(contact.includes("+91 836 841 0417"),"Displayed WhatsApp number missing");
assert(css.includes(".useful-bits"),"Useful-bits styling missing");
assert(css.includes(".service-grid"),"Services styling missing");
assert(css.includes(".review-empty-state"),"Reviews styling missing");
assert(css.includes("object-fit:contain"),"Full media visibility missing");
assert(css.includes("@media(max-width:700px)"),"Mobile layout missing");
new vm.Script(js,{filename:"atelier.js"});
const worker=JSON.parse(read("wrangler.jsonc"));
assert.equal(worker.assets.directory,"./");
console.log("PASS: eight-page Mamtu site, monogram, useful profile, growing gallery, unnumbered media, services, honest reviews, WhatsApp + Telegram, mobile styling");