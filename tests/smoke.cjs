const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const read=(p)=>fs.readFileSync(p,'utf8');
const html=read('index.html'),css=read('atelier.css'),js=read('atelier.js'),media=read('media.js');
for(const section of ['home','about','moments','motion','notes','contact'])assert(html.includes('id="'+section+'"'),'Missing section '+section);
for(const id of ['heroMedia','heroNext','heroPrev','heroPause','heroThumbnails','lookbookGrid','featureFilm','contactForm','lightbox','conciergeToggle','mobileNav'])assert(html.includes('id="'+id+'"'),'Missing interaction '+id);
assert(html.includes('noindex,nofollow'),'Preview must stay noindex');
assert(!html.includes('app.js'),'Old page should not load');
for(const p of ['atelier.css','atelier.js','media.js','wrangler.jsonc'])assert(fs.existsSync(p),'Missing '+p);
for(let i=1;i<=6;i++)assert(fs.existsSync('assets/images/art-study-0'+i+'.svg'),'Missing art '+i);
assert(media.includes('heroVideo: ""'),'No unapproved real film should be claimed');
assert(media.includes('contactEmail: ""'),'No fabricated owner email');
assert(js.includes('showSlide(current + 1)'),'Autoplay not present');
assert(js.includes('prefers-reduced-motion'),'Reduced-motion control missing');
assert(js.includes('heroPause'),'Pause control missing');
assert(css.includes('@media(max-width:650px)'),'Mobile styles missing');
assert(!/<script[^>]*src=["']https?:\/\//.test(html),'No remote third-party scripts expected');
for(const name of ['atelier.js','media.js'])new vm.Script(read(name),{filename:name});
const wrangler=JSON.parse(read('wrangler.jsonc'));
assert.equal(wrangler.assets.directory,'./');
assert.equal(wrangler.workers_dev,true);
console.log('PASS: MAMTU cinematic preview HTML, CSS, JS, media, interactions and Worker configuration');
