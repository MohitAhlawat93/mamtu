for(const page of pages){
  assert(fs.existsSync(page),"Missing "+page);
  const content=read(page);
  assert(content.includes('name="viewport"'),"Mobile viewport missing: "+page);
  assert(content.includes('name="robots" content="noindex,nofollow"'),"Staging indexing accidentally enabled: "+page);
  assert(content.includes('href="/atelier.css?v=editorial-20261120-v3"'),"Versioned CSS missing: "+page);
  assert(content.includes('src="/atelier.js?v=editorial-20261120-v3"'),"Versioned JS missing: "+page);
  assert(content.includes('href="/assistant.css?v=rag-20261120"'),"Assistant CSS missing: "+page);
  assert(content.includes('src="/assistant.js?v=rag-20261120"'),"Assistant JS missing: "+page);
  assert(content.includes('/assets/mark.svg'),"Mamtu brand mark missing: "+page);
  assert(content.includes('https://wa.me/918368410417'),"WhatsApp missing: "+page);
  assert(content.includes('https://t.me/mistressmamtu'),"Telegram missing: "+page);
  for(const link of pages)assert(content.includes('href="/'+link+'"'),"Navigation missing "+link+" in "+page);
  assert(!content.includes("paryavarn complex"),"Private residential detail published: "+page);
  assert(!/PHOTO\s+0\d/i.test(content),"Visible numbered photo label remains: "+page);
  assert(!/VIDEO\s+0\d/i.test(content),"Visible numbered video label remains: "+page);
  assert(!/eight photos,? eight moods/i.test(content),"Fixed-size gallery slogan remains: "+page);
  assert(!content.includes("PRIVATE PREVIEW"),"Testing copy remains: "+page);
}
